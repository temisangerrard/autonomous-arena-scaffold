import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const url = process.env.MANCHESTER_URL || 'http://localhost:5188/manchester/';
const label = new URL(url).hostname === 'localhost' ? 'local' : 'live';
const out = `output/manchester/${label}`;
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader'] });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
  const response = await page.goto(url);
  assert.equal(response.status(), 200);
  await page.waitForFunction(() => typeof window.render_game_to_text === 'function');
  const read = () => page.evaluate(() => JSON.parse(window.render_game_to_text()));
  const initial = await read();
  await page.click('#trail-start');
  const joy = await page.locator('#joystick').boundingBox();
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent', { type:'touchStart', touchPoints:[{ x:joy.x+joy.width/2, y:joy.y+5 }] });
  await page.evaluate(() => window.advanceTime(1000));
  await cdp.send('Input.dispatchTouchEvent', { type:'touchCancel', touchPoints:[] });
  const moved = await read();
  assert.ok(Math.hypot(moved.player.x-initial.player.x,moved.player.z-initial.player.z)>3);
  await page.evaluate(() => window.advanceTime(1000));
  assert.deepEqual((await read()).player, moved.player);
  assert.equal(await page.locator('body').getAttribute('class'), 'exploring');
  await page.screenshot({ path:`${out}/mobile.png` });
  await page.click('#tram-open');
  await page.screenshot({ path:`${out}/tram.png` });
  await page.click('[data-id="trafford"]');
  await page.waitForSelector('#tram-leave'); await page.evaluate(() => window.advanceTime(21000)); await page.click('#tram-leave');
  assert.equal((await read()).district, 'trafford');
  // Native keyboard input after dialog focus returns to the tram button.
  const beforeKey = await read();
  await page.keyboard.down('ArrowUp');
  await page.evaluate(() => window.advanceTime(600));
  await page.keyboard.up('ArrowUp');
  assert.ok(Math.hypot((await read()).player.x-beforeKey.player.x,(await read()).player.z-beforeKey.player.z)>2);
  await page.setViewportSize({ width:844,height:390 });
  await page.evaluate(() => window.advanceTime(20));
  await page.screenshot({ path:`${out}/landscape.png` });
  await page.setViewportSize({ width:1440,height:900 });
  await page.click('#tram-open'); await page.click('[data-id="quays"]');
  await page.waitForSelector('#tram-leave'); await page.evaluate(() => window.advanceTime(21000)); await page.click('#tram-leave');
  await page.screenshot({ path:`${out}/desktop.png` });
  assert.deepEqual(errors, []);
  const result = { url, passed:true, checks:['HTTP 200','world loaded','mobile touch movement','touch cancellation','compact gameplay heading','tram travel','keyboard after dialog close','portrait and landscape'], renderer:(await read()).renderer };
  await writeFile(`${out}/report.json`, JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
} finally { await browser.close(); }
